#!/usr/bin/env python3
"""Generate a complete `fm` CLI reference from two sources that can disagree.

`fm` is a Swift ArgumentParser app. The hidden `--experimental-dump-help` flag
emits the entire command/subcommand/option tree as JSON in a single call. That
dump is not always current: on 27.0.1 (26A434) it still listed `--nested` for
`fm schema object` while the binary accepts only `--object`. So each leaf
command's own `--help` is captured too, ANSI colour stripped, and the flags the
two sources name are compared. A disagreement is printed as a flagged note and
never resolved silently, so a change in either source shows up in the diff.

Usage:
    tools/gen-fm-docs.py                 # writes docs/fm-reference.md
    tools/gen-fm-docs.py --fm /usr/bin/fm --outdir docs
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
FLAG = re.compile(r"(?<![\w-])(--?[A-Za-z][\w-]*)")
# An option row in `--help`: exactly four spaces, then a flag. Usage lines start
# with `%`, and their continuation lines are indented further, so neither matches.
HELP_ROW = re.compile(r"^ {4}(-[^\s,]+(?:, -[^\s,]+)*)")
# An option row inside a dump `discussion`: two spaces, then a long flag.
DISC_ROW = re.compile(r"^ {2}(--[\w-]+)")


def dump_help(fm_bin: str) -> dict:
    out = subprocess.run(
        [fm_bin, "--experimental-dump-help"],
        capture_output=True, text=True, check=True,
    ).stdout
    return json.loads(out)["command"]


def leaf_help(fm_bin: str, name: str) -> str:
    argv = [fm_bin] + name.split()[1:] + ["--help"]
    r = subprocess.run(argv, capture_output=True, text=True)
    text = ANSI.sub("", r.stdout + r.stderr)
    return "\n".join(line.rstrip() for line in text.strip("\n").splitlines())


def dump_flags(cmd: dict) -> set:
    flags = set()
    for a in cmd.get("arguments", []):
        # Hidden arguments never appear in `--help`, so they cannot disagree.
        if a.get("kind") == "positional" or not a.get("shouldDisplay", True):
            continue
        for n in a.get("names", []):
            flags.add(("--" if n["kind"] == "long" else "-") + n["name"])
    for line in cmd.get("discussion", "").splitlines():
        m = DISC_ROW.match(line)
        if m:
            flags.add(m.group(1))
    return flags


def help_flags(text: str) -> set:
    flags = set()
    for line in text.splitlines():
        m = HELP_ROW.match(line)
        if m:
            for f in FLAG.findall(m.group(1).replace("--[no-]", "--")):
                flags.add(f)
            # `--[no-]stream` names both `--stream` and `--no-stream`.
            for f in re.findall(r"--\[no-\]([\w-]+)", m.group(1)):
                flags.update({f"--{f}", f"--no-{f}"})
    return flags


def option_label(a: dict) -> str:
    names = a.get("names", [])
    kind = a.get("kind", "")
    vn = a.get("valueName", "")
    if kind == "positional":
        return f"<{vn}>"
    def fmt(n):
        return ("--" if n["kind"] == "long" else "-") + n["name"]
    label = ", ".join(fmt(n) for n in names)
    if kind == "option":
        label += f" <{vn}>"
    return label


def iter_commands(cmd: dict, path=None):
    path = path or []
    yield " ".join(path + [cmd["commandName"]]), cmd
    for sub in cmd.get("subcommands", []):
        yield from iter_commands(sub, path + [cmd["commandName"]])


def render_md(root: dict, helps: dict) -> str:
    out = ["# `fm` — Apple Foundation Models CLI: Complete Reference\n",
           "_Auto-generated by `tools/gen-fm-docs.py` from "
           "`fm --experimental-dump-help` and each leaf command's `--help`. "
           "Do not edit by hand._\n",
           "Grep `DUMP/HELP MISMATCH` for flags the two sources disagree on.\n"]
    for name, cmd in iter_commands(root):
        out.append(f"\n## `{name}`\n")
        if cmd.get("abstract"):
            out.append(cmd["abstract"] + "\n")
        if cmd.get("discussion"):
            out.append("\n```\n" + cmd["discussion"].rstrip() + "\n```\n")
        args = [a for a in cmd.get("arguments", []) if a.get("shouldDisplay", True)]
        if args:
            out.append("\n| Option | Description |\n|---|---|")
            for a in args:
                dv = a.get("defaultValue")
                extra = f" _(default: `{dv}`)_" if dv else ""
                out.append(f"| `{option_label(a)}` | {a.get('abstract','')}{extra} |")
        if name in helps:
            text = helps[name]
            d, h = dump_flags(cmd), help_flags(text)
            only_dump, only_help = sorted(d - h), sorted(h - d)
            if only_dump or only_help:
                out.append(f"\n> **DUMP/HELP MISMATCH** in `{name}`: the dump and "
                           "`--help` name different flags. Trust neither blindly; "
                           "test the binary.")
                if only_dump:
                    out.append("> - only in dump: "
                               + ", ".join(f"`{f}`" for f in only_dump))
                if only_help:
                    out.append("> - only in `--help`: "
                               + ", ".join(f"`{f}`" for f in only_help))
            out.append(f"\n`{name} --help`:\n\n```\n{text}\n```\n")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fm", default="/usr/bin/fm", help="path to the fm binary")
    ap.add_argument("--outdir", default="docs", help="output directory")
    args = ap.parse_args()

    root = dump_help(args.fm)
    helps = {name: leaf_help(args.fm, name)
             for name, cmd in iter_commands(root) if not cmd.get("subcommands")}
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    md_path = outdir / "fm-reference.md"
    md_path.write_text(render_md(root, helps))
    print(f"wrote {md_path}")


if __name__ == "__main__":
    sys.exit(main())
